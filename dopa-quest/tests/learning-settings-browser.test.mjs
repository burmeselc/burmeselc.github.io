import test from 'node:test';
import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const URL=process.env.DOPA_TEST_URL||'http://127.0.0.1:8123/dopa-quest/';

for(const height of [667,844])test('mobile study setup groups and keeps preferences at '+height+'px',async()=>{
 const browser=await chromium.launch({headless:true});
 try{
  const page=await browser.newPage({viewport:{width:375,height},isMobile:true,hasTouch:true});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(URL,{waitUntil:'domcontentloaded'});
  await page.waitForFunction(()=>document.body.classList.contains('dopa-ui-ready')&&!!window.DOPA_FLASH_UI);
  const before=await page.evaluate(()=>window.DOPA_SYNC_API.snapshot());
  await page.locator('[data-dopa-route="quest"]').click();
  assert.equal(await page.locator('#dopaQuestBasics').isVisible(),true);
  assert.equal(await page.locator('#questAdvancedSettings').evaluate(e=>e.open),false);
  assert.equal(await page.locator('#start').isVisible(),true);
  assert.equal(await page.locator('#zone').isVisible(),true);
  assert.equal(await page.locator('#semanticCategory').isVisible(),true);
  await page.locator('#direction').selectOption('toJP');
  await page.locator('#roundSize').selectOption('10');
  await page.locator('#questAdvancedSettings > summary').click();
  assert.equal(await page.locator('#speed').isVisible(),true);
  await page.locator('#speed').selectOption('rush');
  await page.locator('#questAdvancedSettings > summary').click();
  await page.locator('[data-dopa-route="cards"]').click();
  assert.equal(await page.locator('#dopaFlashBasics').isVisible(),true);
  assert.equal(await page.locator('#flashAdvancedSettings').evaluate(e=>e.open),false);
  assert.equal(await page.locator('#flashStart').isVisible(),true);
  assert.equal(await page.locator('#flashScope').isVisible(),true);
  await page.locator('#flashDirection').selectOption('production');
  await page.locator('#flashScope').selectOption('new');
  await page.locator('#flashCount').selectOption('10');
  await page.locator('#flashAdvancedSettings > summary').click();
  assert.equal(await page.locator('#flashNewLimit').isVisible(),true);
  assert.equal(await page.locator('#flashReviewLimit').isVisible(),true);
  await page.locator('#flashAdvancedSettings > summary').click();
  await page.locator('[data-dopa-route="quest"]').click();
  assert.equal(await page.locator('#direction').inputValue(),'toJP');
  assert.equal(await page.locator('#roundSize').inputValue(),'10');
  assert.equal(await page.locator('#speed').inputValue(),'rush');
  await page.locator('[data-dopa-route="cards"]').click();
  assert.equal(await page.locator('#flashDirection').inputValue(),'production');
  assert.equal(await page.locator('#flashScope').inputValue(),'new');
  assert.equal(await page.locator('#flashCount').inputValue(),'10');
  const after=await page.evaluate(()=>window.DOPA_SYNC_API.snapshot());
  assert.deepEqual(after.words,before.words);
  assert.deepEqual(after.flashcards,before.flashcards);
  assert.deepEqual(after.vocabularyLibrary,before.vocabularyLibrary);
  assert.deepEqual(after.dailyStats,before.dailyStats);
  await page.reload({waitUntil:'domcontentloaded'});
  await page.waitForFunction(()=>document.body.classList.contains('dopa-ui-ready')&&!!window.DOPA_FLASH_UI);
  await page.locator('[data-dopa-route="cards"]').click();
  assert.equal(await page.locator('#flashDirection').inputValue(),'production');
  assert.equal(await page.locator('#flashScope').inputValue(),'new');
  assert.equal(await page.locator('#flashCount').inputValue(),'10');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  assert.deepEqual(errors,[]);
 }finally{await browser.close()}
});
